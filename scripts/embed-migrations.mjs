#!/usr/bin/env node
// Copies every prisma/migrations/*/migration.sql into src/lib/migrations.generated.ts so the running app can apply them
// without the Prisma CLI or the prisma/ folder (Hostinger deploys only the built app). Runs automatically before `npm run build`.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
const root = new URL("..", import.meta.url).pathname, dir = join(root, "prisma", "migrations");
const names = readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(dir, d.name, "migration.sql"))).map((d) => d.name).sort();
const items = names.map((name) => {
  const sql = readFileSync(join(dir, name, "migration.sql"), "utf8");
  return { name, checksum: createHash("sha256").update(sql).digest("hex"), sql };
});
const out = `// GENERATED by scripts/embed-migrations.mjs from prisma/migrations. Do not edit; it is rebuilt before every build.\nexport const MIGRATIONS: { name: string; checksum: string; sql: string }[] = ${JSON.stringify(items, null, 2)};\n`;
writeFileSync(join(root, "src", "lib", "migrations.generated.ts"), out);
console.log(`Embedded ${items.length} migrations`);
